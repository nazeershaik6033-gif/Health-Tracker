const BY_NAME = new Map<string, Micros>(
  ROWS.map(([name, ...values]) => {
    const micros: Micros = {};
    COLUMNS.forEach((id, i) => {
      micros[id] = values[i];
    });
    return [name, micros];
  }),
);

/** Micronutrients per 100 g for a bundled food, by its exact catalog name. */
export function seedMicrosFor(name: string): Micros | undefined {
  return BY_NAME.get(name);
}

/** Every name this table carries — used to spot drift against the food catalog. */
export function seedMicroNames(): string[] {
  return [...BY_NAME.keys()];
}
